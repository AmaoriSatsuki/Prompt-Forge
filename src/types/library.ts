/**
 * 右侧面板当前显示哪个库（D62 起有多个库，D86 把「词典库」改成「Tag 库」）。
 *
 * - `presets`：普通预设库（点任意颜色块都会回到这里）
 * - `tags`：Tag 库（点色块行里的 `T` 进入；内容是词典导入时派生的词条，
 *   与画师库**同构**：胶囊样式、权重、右键「添加为预设」、分页全都一样）
 * - `artists`：画师库（点 `@` 进入）
 * - `snapshots`：快照库（点 `S` 进入）
 *
 * 单独一个文件是为了让 Store 与组件共用同一个联合类型，
 * 而不是各自抄一份字符串（D85 加第四个视图时就是抄的那份漏了）。
 */
export type LibraryView = 'presets' | 'tags' | 'artists' | 'snapshots';
